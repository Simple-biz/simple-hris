// The colour a payee's bank card is printed in.
//
// Accounting → People → View → Banking renders a person's payout record as a card
// in their own bank's colours, so the bank is recognised before anything is read.
// A tint is a claim about an institution exactly as a logo is, so it follows the
// same rule `payment-catalog-current-banks.md` §7 sets for the artwork:
//
//   **Every colour below is MEASURED off the shipped logo, never recalled.**
//
// `scripts/derive-bank-brand-colors.mts` prints this table from `public/banks/*.png`
// using `dominantInkColor`, and `bank-card-palette.test.ts` re-derives it from those
// same files on every run. A table that drifts from the artwork fails there rather
// than shipping one bank's card in another bank's colour. To add a bank: ship its
// logo, run the script, paste the line.
//
// A bank with no shipped logo (MariBank, Metrobank, Security Bank and SeaBank
// deliberately have none) and a spelling nobody has claimed both get the NEUTRAL
// card. Guessing a colour for them is the same invented equivalence §10.1 forbids,
// just quieter.
//
// CLIENT-SAFE: pure colour maths, no imports.

