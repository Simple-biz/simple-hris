// Downloads the six cursive faces used by the Documents typed-signature mode.
//
// WHY THIS EXISTS
// The typed signature is rasterised on a <canvas>. Canvas 2D does NOT report a
// missing font — fillText silently falls back to the generic family, so an
// unloaded cursive face produces a signature that is not cursive, saved with no
// error anywhere. The only reliable guard is to remove the network from the
// path: the faces are self-hosted, so `document.fonts.load()` either resolves
// against a file we shipped or fails loudly enough for the picker to disable it.
// Pulling them from the Google CDN at request time (the way src/index.css:1
// loads Inter) would reintroduce exactly the silent-fallback case.
//
// It also captures each face's unicode-range, which becomes the coverage
// predicate in signature-fonts.ts — same idea as isCoveredBySubset() in
// src/lib/pdf/fonts.ts. A name carrying a glyph the subset lacks must be
// refused in the UI, not drawn as tofu onto a legal document.
//
// USAGE
//   node scripts/fetch-signature-fonts.mjs
// Re-run only to add a face or pick up an upstream revision; the woff2 files
// and the generated @font-face block are committed.
//
// Licence: all six are SIL Open Font License 1.1.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public', 'fonts', 'signature');

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

/** The faces, in picker order. Distinct enough that nobody has to squint to
 *  tell two apart — formal copperplate → casual → monoline → flourished →
 *  pen-realistic → everyday hand. */
const FACES = [
  { family: 'Great Vibes', slug: 'great-vibes' },
  { family: 'Dancing Script', slug: 'dancing-script' },
  { family: 'Sacramento', slug: 'sacramento' },
  { family: 'Allura', slug: 'allura' },
  { family: 'Homemade Apple', slug: 'homemade-apple' },
  { family: 'Caveat', slug: 'caveat' },
];

/** Only these subsets ship. `latin` covers ASCII + the accented Latin-1 letters
 *  Filipino and Colombian names actually use (ñ, é, á); `latin-ext` adds the
 *  rest of European Latin. Everything beyond that is refused by the coverage
 *  predicate rather than drawn as a blank box. */
const WANTED_SUBSETS = new Set(['latin', 'latin-ext']);

async function fetchText(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`GET ${url} → ${res.status}`);
  return res.text();
}

/** Pull { subset, url, unicodeRange } out of a Google Fonts css2 response.
 *  Each `/* subset *\/` comment precedes exactly one @font-face block. */
function parseFaces(css) {
  const out = [];
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const [, subset, body] = m;
    const url = body.match(/src:\s*url\((https:[^)]+)\)/)?.[1];
    const unicodeRange = body.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim();
    if (url && unicodeRange) out.push({ subset, url, unicodeRange });
  }
  return out;
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const cssParts = [];
  const registry = [];

  for (const face of FACES) {
    const family = face.family.replace(/ /g, '+');
    const css = await fetchText(
      `https://fonts.googleapis.com/css2?family=${family}&display=block`,
    );
    const parsed = parseFaces(css).filter((p) => WANTED_SUBSETS.has(p.subset));
    if (!parsed.length) throw new Error(`No latin subset found for ${face.family}`);

    const ranges = [];
    for (const p of parsed) {
      const filename = `${face.slug}-${p.subset}.woff2`;
      const res = await fetch(p.url, { headers: { 'User-Agent': UA } });
      if (!res.ok) throw new Error(`GET ${p.url} → ${res.status}`);
      const bytes = Buffer.from(await res.arrayBuffer());
      fs.writeFileSync(path.join(OUT_DIR, filename), bytes);
      cssParts.push(
        `@font-face {\n` +
          `  font-family: '${face.family}';\n` +
          `  font-style: normal;\n` +
          `  font-weight: 400;\n` +
          `  font-display: block;\n` +
          `  src: url('/fonts/signature/${filename}') format('woff2');\n` +
          `  unicode-range: ${p.unicodeRange};\n` +
          `}`,
      );
      ranges.push(p.unicodeRange);
      console.log(`  ${filename}  ${(bytes.length / 1024).toFixed(1)} KB`);
    }
    registry.push({ slug: face.slug, family: face.family, ranges });
  }

  fs.writeFileSync(
    path.join(OUT_DIR, 'faces.css'),
    `/* GENERATED by scripts/fetch-signature-fonts.mjs — do not edit by hand. */\n\n` +
      cssParts.join('\n\n') +
      '\n',
  );
  fs.writeFileSync(
    path.join(OUT_DIR, 'unicode-ranges.json'),
    JSON.stringify(registry, null, 2) + '\n',
  );
  console.log(`\nWrote faces.css + unicode-ranges.json to ${OUT_DIR}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
